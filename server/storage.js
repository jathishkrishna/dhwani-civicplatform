// ============================================================
// Photo/video storage in Supabase Storage.
//
// Files are still received by multer on local disk first (so fraud.js can hash them),
// then moved to a private Supabase bucket. The URLs stored in the database stay
// "/uploads/<name>", so existing complaints and the frontend need no changes:
// server.js serves /uploads/<name> from local disk if present, otherwise from the bucket.
// ============================================================
const fs = require('fs');
const os = require('os');
const path = require('path');
const sb = require('./supabase');

const BUCKET = process.env.SUPABASE_BUCKET || 'uploads';
const uploadsDir = path.join(__dirname, 'uploads');

const TYPES = {
  '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.png': 'image/png', '.webp': 'image/webp',
  '.gif': 'image/gif', '.mp4': 'video/mp4', '.mov': 'video/quicktime', '.webm': 'video/webm'
};

// Only plain file names generated by multer (digits, dash, dot, extension)
const safeName = (n) => (typeof n === 'string' && /^[\w][\w.-]*$/.test(n) && !n.includes('..')) ? n : null;

// Creates the bucket if it does not exist yet. Call once at start-up.
async function init() {
  const { error } = await sb.storage.createBucket(BUCKET, { public: false });
  if (error && !/already exists|duplicate/i.test(error.message || '') && String(error.statusCode) !== '409') {
    throw new Error(`Could not create/find the Supabase Storage bucket "${BUCKET}": ${error.message}`);
  }
  console.log(`[storage] using Supabase Storage bucket "${BUCKET}"`);
}

// Uploads multer files (from disk) to the bucket, then removes the local copies.
async function persist(files) {
  const list = (files || []).filter(f => f && f.path && f.filename);
  await Promise.all(list.map(async (f) => {
    const buffer = await fs.promises.readFile(f.path);
    const { error } = await sb.storage.from(BUCKET).upload(f.filename, buffer, {
      contentType: f.mimetype || TYPES[path.extname(f.filename).toLowerCase()] || 'application/octet-stream',
      upsert: true
    });
    if (error) throw new Error(`[storage] upload failed for ${f.filename}: ${error.message}`);
    fs.unlink(f.path, () => {});
  }));
}

// Downloads one file from the bucket. Returns { buffer, type } or null if it does not exist.
async function fetchFile(name) {
  const n = safeName(name);
  if (!n) return null;
  const { data, error } = await sb.storage.from(BUCKET).download(n);
  if (error || !data) return null;
  return {
    buffer: Buffer.from(await data.arrayBuffer()),
    type: data.type || TYPES[path.extname(n).toLowerCase()] || 'application/octet-stream'
  };
}

// Best effort: delete files from the bucket (names are the part after /uploads/)
async function removeMany(names) {
  const list = (names || []).map(safeName).filter(Boolean);
  if (!list.length) return;
  try { await sb.storage.from(BUCKET).remove(list); } catch (e) { /* never block a delete on this */ }
}

// Runs fn(localPath) with the file on local disk (downloads a temporary copy if needed).
// Returns fn's result, or null if the file cannot be found anywhere.
async function withLocal(name, fn) {
  const n = safeName(name);
  if (!n) return null;
  const local = path.join(uploadsDir, n);
  if (fs.existsSync(local)) return fn(local);

  const f = await fetchFile(n);
  if (!f) return null;
  const tmp = path.join(os.tmpdir(), `dhwani-${Date.now()}-${n}`);
  await fs.promises.writeFile(tmp, f.buffer);
  try { return await fn(tmp); }
  finally { fs.unlink(tmp, () => {}); }
}

module.exports = { init, persist, fetchFile, removeMany, withLocal };
